def line_pick(text, pos, vals, after=False):
    starts = [0] + [i + 1 for i, ch in enumerate(text) if ch == '\n']
    li = max(i for i, st in enumerate(starts) if st <= pos)
    bounds = lambda i: (starts[i], starts[i + 1] if i + 1 < len(starts) else len(text))
    def in_line(i):
        a, b = bounds(i)
        # في النص العربي المستخرج تسبق النسبة وصفها غالبًا («%5 إيجار»)، فالأقرب قبل المرسى أولًا ثم بعده
        return sorted([((0 if p <= pos else 1) if not after else (0 if p > pos else 1), abs(p - pos), -RANK[k], v, k) for v, p, k in vals if a <= p < b])
    same = in_line(li)
    words = [c for c in same if c[4] == 'كتابة' and c[1] < 80]
    if words: words.sort(key=lambda c: c[1]); return words[0][3], words[0][4]  # المكتوب بالحروف أوثق من الرقم المقروء ضوئيًا
    if same: return same[0][3], same[0][4]
    for j in (li - 1, li + 1):
        if 0 <= j < len(starts):
            a, b = bounds(j)
            if re.fullmatch(r'\s*[\(\)]?\s*%?\s?\d{1,3}(?:[.,]\d+)?\s?%?\s*[\(\)]?\s*', text[a:b]):
                c = in_line(j)
                if c: return c[0][3], c[0][4]
    return None


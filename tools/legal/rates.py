import gzip, json, re, sys

def norm(s):
    s = re.sub('[ً-ْـ]', '', s)
    s = re.sub('[أإآ]', 'ا', s).replace('ى', 'ي').replace('ة', 'ه')
    return s.translate(str.maketrans('٠١٢٣٤٥٦٧٨٩', '0123456789'))

UNITS = {'واحد': 1, 'اثنين': 2, 'اثنان': 2, 'ثلاثه': 3, 'ثلاث': 3, 'اربعه': 4, 'خمسه': 5, 'خمس': 5, 'سته': 6, 'سبعه': 7, 'ثمانيه': 8, 'تسعه': 9, 'عشره': 10, 'عشر': 10}
TENS = {'عشرون': 20, 'عشرين': 20, 'ثلاثون': 30, 'ثلاثين': 30, 'اربعون': 40, 'اربعين': 40, 'خمسون': 50, 'خمسين': 50, 'ستون': 60, 'ستين': 60, 'سبعون': 70, 'سبعين': 70, 'ثمانون': 80, 'ثمانين': 80, 'تسعون': 90, 'تسعين': 90}
PCT_WORD = r'(?:بال|في ال)(?:مئه|مائه|ماءه|مايه|مثه|مثئه)'
WORDNUM = r'((?:(?:و)?(?:' + '|'.join(sorted(list(UNITS) + list(TENS) + ['مائه', 'مئه', 'نصف'], key=len, reverse=True)) + r')\s*){1,4})'

def words_value(w):
    toks = re.findall(r'و?(' + '|'.join(sorted(list(UNITS) + list(TENS) + ['مائه', 'مئه', 'نصف'], key=len, reverse=True)) + ')', w)
    v = 0.0
    for t in toks:
        if t in ('مائه', 'مئه'): v = (v or 1) * 100
        elif t == 'نصف': v += 0.5
        elif t in TENS: v += TENS[t]
        elif t in UNITS: v += UNITS[t]
    return v or None

def percents(text):
    """[(القيمة، الموضع، الطريقة)] لكل نسبة في النص"""
    t = norm(text); out = []
    for m in re.finditer(WORDNUM + r'\s*' + PCT_WORD, t):
        v = words_value(m.group(1))
        if v: out.append((v, m.start(), 'كتابة'))
    for m in re.finditer(r'%', t):
        aft = re.match(r'\s?\(?\s?(\d{1,3}(?:[.,]\d{1,4})?)', t[m.end():m.end() + 10])
        bef = re.search(r'(?<![\d.])(\d{1,3}(?:[.,]\d{1,4})?)\s?\)?\s?$', t[max(0, m.start() - 10):m.start()])
        g = aft or bef
        if not g: continue
        raw = g.group(1).replace(',', '.')
        v = float(raw)
        if '.' in raw and v >= 5 and len(raw) == 3: v = float(raw[::-1])  # %5.2 معكوسة = 2.5
        out.append((v, m.start(), 'رقم'))
    for m in re.finditer(r'\(\s?90(\d{1,3})\s?\)|\b90(100|50|25|20|15|10)\b|\(\s?(?:0|9)0?5\s?\)', t):
        g = m.group(1) or m.group(2)
        out.append((float(g) if g else 5.0, m.start(), 'قراءة ضوئية'))
    return out

def amounts(text):
    t = norm(text); out = []
    for m in re.finditer(r'\(?\s?(\d{1,3}(?:[,.]\d{3})+|\d{4,7})\s?\)?\s*(?:\S+\s+){0,3}ريال', t):
        out.append((float(re.sub(r'[,.]', '', m.group(1))), m.start(), 'رقم'))
    for m in re.finditer(r'(عشره|عشرين|خمسين|مائه)\s*(?:الف|الاف)\s*ريال|(عشرون|عشرين)\s*(?:الف|الاف)', t):
        w = (m.group(1) or m.group(2)); v = {'عشره': 10000, 'عشرين': 20000, 'عشرون': 20000, 'خمسين': 50000, 'مائه': 100000}[w]
        out.append((float(v), m.start(), 'كتابة'))
    return out

